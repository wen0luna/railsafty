export type MessageKey = keyof typeof messages;
export type Language = 'zh' | 'en';
export interface LocalizedMessage {
  key: MessageKey;
  params?: Record<string, string | number | LocalizedMessage>;
}
export interface LanguageStorage {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}

// Retain the original key so rebranding does not reset saved language preferences.
export const LANGUAGE_STORAGE_KEY = 'railguard.language';
let language: Language = 'zh';

export function getLanguage(): Language { return language; }
export function getLocale(): string { return language === 'en' ? 'en-GB' : 'zh-CN'; }
export function setLanguage(next: Language): void { language = next; }

export function restoreLanguage(storage: LanguageStorage | null): void {
  language = 'zh';
  if (!storage) return;
  try {
    const stored = storage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored === 'zh' || stored === 'en') language = stored;
    else if (stored !== null) console.warn('Unsupported saved interface language:', stored);
  } catch (error) {
    console.warn('Unable to read the saved interface language:', error);
  }
}

export function saveLanguage(storage: LanguageStorage | null): boolean {
  if (!storage) return false;
  try {
    storage.setItem(LANGUAGE_STORAGE_KEY, language);
    return true;
  } catch (error) {
    console.warn('Unable to save the interface language:', error);
    return false;
  }
}

export function t(key: MessageKey, params: LocalizedMessage['params'] = {}): string {
  const template = messages[key][language === 'en' ? 1 : 0];
  return template.replace(/\{(\w+)\}/g, (_token, name: string) => {
    const value = params[name];
    if (value === undefined) throw new Error(`Missing translation parameter "${name}" for "${key}".`);
    return typeof value === 'object' ? translateMessage(value) : String(value);
  });
}

export function message(key: MessageKey, params?: LocalizedMessage['params']): LocalizedMessage {
  return params ? { key, params } : { key };
}

export function translateMessage(value: LocalizedMessage): string {
  return t(value.key, value.params);
}

function escapeHtml(value: string): string {
  return value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

export function text(key: MessageKey): string {
  return `<span data-i18n="${key}">${escapeHtml(t(key))}</span>`;
}

const translatedAttributes = ['aria-label', 'title', 'placeholder'] as const;
export function attributes(key: MessageKey, ...names: (typeof translatedAttributes[number])[]): string {
  return names.map((name) => `data-i18n-${name}="${key}" ${name}="${escapeHtml(t(key))}"`).join(' ');
}

function messageKey(value: string): MessageKey {
  if (!Object.hasOwn(messages, value)) throw new Error(`Unknown interface message: "${value}".`);
  return value as MessageKey;
}

export function applyTranslations(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((element) => {
    element.textContent = t(messageKey(element.dataset.i18n!));
  });
  for (const name of translatedAttributes) {
    root.querySelectorAll<HTMLElement>(`[data-i18n-${name}]`).forEach((element) => {
      element.setAttribute(name, t(messageKey(element.getAttribute(`data-i18n-${name}`)!)));
    });
  }
}
